"""Generate ``openstat/rngtables.h`` from :mod:`openstat.rng_tables`.

The C fast path needs the ziggurat tables as C constants.  They are
generated from the Python tables so that there is exactly one source of
truth for the numbers: the tables in :mod:`openstat.rng_tables`, which were
recovered from the shipped Stata binary.

Run this after changing :mod:`openstat.rng_tables`::

    python -m openstat._rngtables
"""
from __future__ import annotations

import pathlib

HEADER = """/* Generated by openstat/_rngtables.py from openstat/rng_tables.py.
 *
 * The ziggurat tables of Stata's normal generator, as C constants.
 * Do not edit by hand: run ``python -m openstat._rngtables`` instead.
 */
#ifndef OPENSTAT_RNGTABLES_H
#define OPENSTAT_RNGTABLES_H

"""


def _array(name: str, values, per_line: int = 4) -> str:
    lines = [f"static const double {name}[{len(values)}] = {{"]
    for start in range(0, len(values), per_line):
        chunk = values[start:start + per_line]
        lines.append("    " + ", ".join(repr(float(v)) for v in chunk) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def _load_tables():
    """Load :mod:`openstat.rng_tables` without importing the package.

    The build runs in an isolated environment that has no numpy, and
    importing ``openstat`` would pull numpy in through the package's
    ``__init__``.  The table module itself has no dependencies, so it is
    loaded straight from its file.
    """
    import importlib.util

    path = pathlib.Path(__file__).with_name("rng_tables.py")
    spec = importlib.util.spec_from_file_location("_openstat_rng_tables", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def render() -> str:
    rng_tables = _load_tables()

    parts = [HEADER]
    parts.append(_array("Z_A", rng_tables.A))
    parts.append(_array("Z_B", rng_tables.B))
    parts.append(_array("Z_C", rng_tables.C))
    parts.append(_array("Z_D", rng_tables.D))
    parts.append(_array("Z_E", rng_tables.E))
    parts.append(_array("Z_F", rng_tables.F))
    parts.append(_array("Z_T", rng_tables.T))
    parts.append(f"#define Z_STRIP {rng_tables.STRIP!r}\n")
    parts.append(f"#define Z_E_OUTER {rng_tables.E_OUTER!r}\n")
    parts.append(f"#define Z_TAIL_LIMIT {rng_tables.TAIL_LIMIT!r}\n")
    parts.append(f"#define Z_TAIL_SQUARE {rng_tables.TAIL_SQUARE!r}\n")
    parts.append("#endif /* OPENSTAT_RNGTABLES_H */\n")
    return "\n".join(parts)


def main() -> int:
    target = pathlib.Path(__file__).with_name("rngtables.h")
    target.write_text(render(), encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
