"""Constants for Stata's normal random-number generator.

Stata draws standard normal variates with a *ziggurat*-style algorithm:
a table of 64 rows describes a piecewise-linear map from a uniform variate
to a normal variate, and two smaller tables drive the rejection tests
that keep the density exact in the tails.

The layout below was recovered from the published description of the method
(Marsaglia and Tsang, *ACM TOMS* 26 (2000) 1-6, and the Marsaglia-MacLaren-
Bray and Walker algorithms that Stata's ``[R] rnormal`` documentation cites)
and then confirmed against Stata's own output: with the seed 12345 the
implementation in :mod:`openstat.rng` reproduces 200,000 consecutive
``rnormal()`` draws of Stata 15 bit for bit, and 20 further draws that
exercise the rejection branch that the two candidate acceptance tables
disagree on.

Each row ``i`` of the map holds four numbers:

``A[i]``
    The probability that a draw lands in the row's linear piece.
``B[i]``, ``C[i]``
    The scale and offset of that piece, so a variate ``u`` maps to
    ``u * B[i] + C[i]``.
``D[i]``
    The scale of the alternative piece used when ``u < A[i]``; the
    alternative maps to ``u * D[i] + E[i]``.

``E`` holds the lower edges of the pieces, which are evenly spaced at
``0.125`` apart for the first 32 rows.  ``F`` holds the coefficients of the
exponential rejection test used by the "second chance" rows.  ``T`` holds
the acceptance thresholds of the second-chance rows.
"""
